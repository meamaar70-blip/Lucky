const FONT_PATH = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf';

/** تبدیل متن منطقی به ترتیب دیداری (کلمات برعکس، یک فاصله)) */
function visual(text) {
  // فاصلهٔ پایانی لازم است؛ بدون آن pdf.js نخستین فاصلهٔ کلمه‌ها را در استخراج حذف می‌کند
  return String(text).trim().split(/\s+/).reverse().join(' ') + ' ';
}

/** شکستن متن به خطوط کوتاه (بدون شکستن کلمه) تا در عرض صفحه جا شود */
function chunkText(text, maxLen = 46) {
  const out = [];
  let cur = '';
  for (const word of String(text).split(/\s+/).filter(Boolean)) {
    if (!cur) cur = word;
    else if ((cur + ' ' + word).length <= maxLen) cur += ' ' + word;
    else { out.push(cur); cur = word; }
  }
  if (cur) out.push(cur);
  return out;
}

/**
 * ساخت PDF کتاب نمونه
 * @param {string} outPath مسیر خروجی
 * @returns {Promise<string>}
 */
export async function makeSamplePdf(outPath) {
  const PDFDocument = (await import('pdfkit')).default;
  fs.mkdirSync(outPath.replace(/\/[^/]+$/, '') || '.', { recursive: true });

  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: 'A5',
      margins: { top: 42, bottom: 42, left: 38, right: 38 },
      info: { Title: 'مبانی یادگیری و مطالعه', Author: 'Lucky Study' },
    });
    const stream = fs.createWriteStream(outPath);
    doc.pipe(stream);
    doc.registerFont('fa', FONT_PATH);

    SAMPLE_CHAPTERS.forEach((chapter, ci) => {
      if (ci > 0) doc.addPage();
      doc.font('fa').fontSize(13).fillColor('#111827')
        .text(visual(chapter.title), { align: 'right' });
      doc.moveDown(0.7);

      for (const paragraph of chapter.paragraphs) {
        for (const line of chunkText(paragraph)) {
          if (doc.y > 372) doc.addPage();
          doc.font('fa').fontSize(8.5).fillColor('#1f2937')
            .text(visual(line), { align: 'right', lineGap: 1.5 });
        }
        doc.moveDown(0.5);
      }
    });

    doc.end();
    stream.on('finish', () => resolve(outPath));
    stream.on('error', reject);
  });
}

/**
 * اعتبارسنجی: متن استخراج‌شده باید با متن اصلی (پس از نرمال‌سازی) هم‌خوان باشد.
 * @param {string} pdfPath
 * @returns {Promise<{ok:boolean, coverage:number, missing:string[]}>}
 */
export async function verifySamplePdf(pdfPath) {
  const { extractPdf } = await import('../server/lib/pdf.js');
  const { normalize } = await import('../server/lib/persian.js');
  // در PDF های فارسی، ترکیب «لا» گاهی به صورت «ال» استخراج می‌شود (مثل معموال).
  // برای سنجش پوشش، هر دو شکل را یکسان می‌کنیم.
  const loose = (t) =>
    normalize(String(t).replace(/\u200c/g, ' '))
      .replace(/ال/g, 'لا')
      .replace(/\s+/g, ' ');
  const res = await extractPdf(pdfPath);
  const extracted = loose(res.pages.map((p) => p.lines.join(' ')).join(' '));

  const missing = [];
  let total = 0;
  let found = 0;
  for (const ch of SAMPLE_CHAPTERS) {
    for (const p of ch.paragraphs) {
      for (const line of chunkText(p)) {
        total += 1;
        const probe = loose(line).split(' ').slice(0, 4).join(' ');
        if (extracted.includes(probe)) found += 1;
        else missing.push(probe);
      }
    }
  }
  return { ok: total > 0 && found / total >= 0.97, coverage: total ? found / total : 0, missing: missing.slice(0, 5) };
}

// اجرای مستقیم: node scripts/sample-book.mjs [out.pdf]
if (process.argv[1] && process.argv[1].endsWith('sample-book.mjs')) {
  const out = process.argv[2] ?? 'samples/sample-book.pdf';
  await makeSamplePdf(out);
  const v = await verifySamplePdf(out);
  const kb = (fs.statSync(out).size / 1024).toFixed(0);
  console.log(`✓ PDF نمونه: ${out} (${kb} کیلوبایت) — پوشش متن: ${(v.coverage * 100).toFixed(0)}%`);
  if (!v.ok) console.log('  خطوط گم‌شده:', v.missing.join(' / '));
}
